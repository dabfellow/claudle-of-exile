export function describeStat(key: StatKey, value: number): string {
  return TEXT[key]?.(value) ?? `${key}: ${value}`;
}

export function describeStats(stats: Partial<Record<StatKey, number>>): string[] {
  return Object.entries(stats).map(([k, v]) => describeStat(k as StatKey, v ?? 0));
}
